// Per-vehicle report (Step 8): npm run vehicle-report -- <vehicle_id> (collects lab results, then runs this).
// Direct use: tsx tools/sheet-report.ts <vehicle_id> [lab-results.json] -> docs/vehicle_reports/<vehicle_id>.md
import fs from 'node:fs';
import path from 'node:path';
import type { Conf, Needs, VehicleSheet } from '../src/sheets/schema';
import { REFS_DIR, ROOT, crossCheck, loadSheets, validate, confSummary, type Issue, type PointsFile } from './sheets-lib';

const id = process.argv[2];
const labPath = process.argv[3];
const s = loadSheets().find((x) => x.id === id);
if (!s) { console.error(`no sheet data/vehicle_sheets/${id}.json`); process.exit(1); }
const lab = labPath && fs.existsSync(labPath) ? JSON.parse(fs.readFileSync(labPath, 'utf8')) : null;
const dir = path.join(REFS_DIR, id);
const present = fs.existsSync(dir) ? fs.readdirSync(dir) : null;

// Validator output
const issues: Issue[] = validate(s, present);
const points: PointsFile[] = (present ?? []).filter((f) => f.endsWith('.points.json')).map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
issues.push(...crossCheck(s, points));

// Every C/X value, with where it lives and what would settle it.
interface Weak { at: string; value: string; conf: Conf; src: string; needs?: Needs }
const weak: Weak[] = [];
const fmt = (v: unknown) => JSON.stringify(v).replace(/,/g, ', ');
for (const [k, d] of Object.entries(s.dimensions)) if (d.conf === 'C' || d.conf === 'X') weak.push({ at: `dimensions.${k}`, value: `${d.value}`, conf: d.conf, src: d.src, needs: d.needs });
for (const [k, o] of Object.entries(s.outlines)) {
  const w = o.points.filter((p) => p[2].conf === 'C' || p[2].conf === 'X');
  if (w.length) weak.push({ at: `outlines.${k} (${w.length} of ${o.points.length} points)`, value: w.map((p) => `[${p[0]}, ${p[1]}]${p[2].conf}`).join(' '), conf: w.some((p) => p[2].conf === 'X') ? 'X' : 'C', src: o.src, needs: o.needs });
}
const one = (at: string, o: { conf: Conf; src: string; needs?: Needs } | undefined, value: unknown) => { if (o && (o.conf === 'C' || o.conf === 'X')) weak.push({ at, value: fmt(value), conf: o.conf, src: o.src, needs: o.needs }); };
if (s.turret) one('turret.pivot', s.turret, s.turret.pivot);
if (s.gun) { one('gun', s.gun, { from_x: s.gun.from_x, muzzle_x: s.gun.muzzle_x, dia: s.gun.dia }); for (const f of s.gun.fittings) one(`gun.${f.kind}`, f, { x: f.x, len: f.len, dia: f.dia }); }
for (const [k, g] of Object.entries(s.running_gear)) if (g) { const { conf, src, needs, ...rest } = g; one(`running_gear.${k}`, { conf, src, needs }, rest); }
for (const r of [['rotor', s.rotor], ['rotor2', s.rotor2], ['tail_rotor', s.tail_rotor]] as const) if (r[1]) { const { conf, src, needs, ...rest } = r[1]; one(r[0], { conf, src, needs }, rest); }
for (const p of s.parts) one(`parts.${p.id}`, p, p.pos ?? p.points);
for (const [k, h] of Object.entries(s.hooks)) if (h) one(`hooks.${k}`, h, h.value);

// Which reference would raise confidence most: count weak items (and pending details) by the view that settles them.
const score: Record<string, number> = {};
for (const w of weak) score[w.needs ?? 'top'] = (score[w.needs ?? 'top'] ?? 0) + (w.conf === 'X' ? 2 : 1);
for (const d of s.detail_inventory) if (d.status === 'pending' || d.status === 'unconfirmed') score[d.needs ?? 'top'] = (score[d.needs ?? 'top'] ?? 0) + 1;
const VIEW_TEXT: Record<string, string> = {
  top: 'a true top plan view (scale drawing with a scale bar, or a straight-down photo of a model)',
  side: 'a clean side profile (orthographic drawing or a straight-on photo at hull-centre height)',
  rear: 'a rear-deck / engine-deck photo from above and behind',
  front: 'a straight-on front view',
  detail: 'detail photos of the specific fittings listed',
};
const ranked = Object.entries(score).sort((a, b) => b[1] - a[1]);

const L: string[] = [];
const c = confSummary(s);
L.push(`# ${s.name} (\`${s.id}\`) vehicle report`, '', `<!-- GENERATED by npm run vehicle-report -- ${s.id}. Edit the sheet, then regenerate. -->`, '');
L.push(`- **Variant drawn:** ${s.variant}`, `- **Sheet status:** ${s.status}`, `- **Confidence tags:** A ${c.A}, B ${c.B}, C ${c.C}, X ${c.X}`,
  `- **References measured:** ${s.references.length ? s.references.map((r) => `${r.file} (${r.view}${r.calibrated_to ? `, calibrated to ${r.calibrated_to}` : ', not calibrated'})`).join('; ') : 'none'}`, '');
L.push('## Validator (npm run check-sheets)', '', '```');
const e = issues.filter((i) => i.level === 'error').length;
L.push(`${s.id}: ${e ? `FAIL ${e} error${e > 1 ? 's' : ''}` : 'PASS'}, ${issues.length - e} warning(s)`, ...issues.map((i) => `${i.level === 'error' ? 'ERROR' : 'warn '} ${i.msg}`), '```', '');
L.push('## Comparison against the references', '');
const cmp = lab?.compare as Array<{ image: string; view: string; result: Record<string, unknown> }> | undefined;
if (!cmp?.length) L.push('Not run: no calibrated reference with an approved mask or marks in `refs/' + s.id + '/` yet.', '');
else for (const r of cmp) {
  const res = r.result as { iou?: number; meanCm?: number; maxCm?: number; heightM?: number; parts: Array<{ id: string; conf?: string; errCm: number; counted: boolean; pass: boolean }>; failures: string[] };
  L.push(`### ${r.image} (${r.view})`, '');
  if (res.iou !== undefined) L.push(`- Silhouette IoU: ${Number.isFinite(res.iou) ? res.iou.toFixed(4) : '–'} (pass >= 0.95)`, `- Outline error: mean ${res.meanCm?.toFixed(1)} cm, max ${res.maxCm?.toFixed(1)} cm (pass <= 8 cm)`);
  if (res.heightM !== undefined) L.push(`- Height ground to turret top: ${Number.isFinite(res.heightM) ? res.heightM.toFixed(3) + ' m' : 'not marked'}`);
  const worst = [...res.parts].sort((a, b) => b.errCm - a.errCm).slice(0, 8);
  if (worst.length) L.push('', '| Part | Conf | Error | Counted | Result |', '|---|---|---|---|---|', ...worst.map((p) => `| ${p.id} | ${p.conf ?? '–'} | ${p.errCm.toFixed(1)} cm | ${p.counted ? 'yes' : 'no (C/X)'} | ${p.counted ? (p.pass ? 'PASS' : 'FAIL') : '–'} |`));
  L.push('', `Failures: ${res.failures.length ? res.failures.join('; ') : 'none'}`, '');
}
L.push('## 64 px recognisability', '');
const conf64 = lab?.confusable as Array<{ a: string; b: string; iou: number }> | undefined;
if (!conf64) L.push('Not run (needs the Sprite Lab via npm run vehicle-report).', '');
else {
  const mine = conf64.filter((x) => x.a === s.id || x.b === s.id).slice(0, 5);
  L.push('Silhouette IoU at 64 px against every other vehicle (legacy game sprites where no sheet exists yet). 0.90 or more needs distinguishing features.', '',
    '| Pair | IoU | Verdict |', '|---|---|---|', ...mine.map((x) => `| ${x.a} / ${x.b} | ${x.iou.toFixed(3)} | ${x.iou >= 0.9 ? 'CHECK' : 'ok'} |`), '');
}
L.push('## Changes from the old sheet', '');
if (!s.changes_from_draft.length) L.push('None.', '');
else L.push('| What | Before | After | Source |', '|---|---|---|---|', ...s.changes_from_draft.map((x) => `| ${x.what} | ${x.before} | ${x.after} | ${x.src} |`), '');
L.push('## Every conf C and X item', '', '| Where | Value | Conf | Settled by | Source |', '|---|---|---|---|---|',
  ...weak.map((w) => `| ${w.at} | ${w.value} | ${w.conf} | ${w.needs ?? 'top'} | ${w.src} |`), '');
L.push('## Details not drawn yet', '', '| Detail | Status | Settled by | Source |', '|---|---|---|---|',
  ...s.detail_inventory.filter((d) => d.status === 'pending' || d.status === 'unconfirmed').map((d) => `| ${d.what} | ${d.status} | ${d.needs ?? '–'} | ${d.src} |`), '');
L.push('## Excluded as post-1980 or unconfirmed for 1980', '', ...(s.excluded_details.length ? s.excluded_details.map((x) => `- ${x}`) : ['- none']), '');
L.push('## Removed (did not belong on this vehicle)', '', ...(s.detail_inventory.filter((d) => d.status === 'removed').map((d) => `- ${d.what}: ${d.src}`) || []), '');
L.push('## Open questions', '', ...s.open_questions.map((q) => `- ${q}`), '');
L.push('## Reference that would raise confidence most', '', ...ranked.map(([v, n], i) => `${i + 1}. **${v}**: ${VIEW_TEXT[v] ?? v} (settles ${n} weighted C/X or pending items)`), '');
if (s.critique?.length) L.push('## Critique of the latest render', '', ...s.critique.map((x) => `- ${x}`), '');
const out = path.join(ROOT, 'docs/vehicle_reports', `${s.id}.md`);
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}`);
