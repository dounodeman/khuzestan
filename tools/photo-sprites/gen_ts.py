import json, sys, glob, os
outdir, dest = sys.argv[1], sys.argv[2]
ents=[]
for f in sorted(glob.glob(f'{outdir}/*.json')):
    n=os.path.basename(f)[:-5]; m=json.load(open(f))
    r=lambda v: round(v,3)
    ents.append(f"""  {n}: {{
    hull: {{ file: '{m['hull']['file']}', w: {r(m['hull']['w_m'])}, h: {r(m['hull']['h_m'])} }},
    turret: {{ file: '{m['turret']['file']}', w: {r(m['turret']['w_m'])}, h: {r(m['turret']['h_m'])}, pivot: [{r(m['turret']['pivot_m'][0])}, {r(m['turret']['pivot_m'][1])}] }},
    pivot: [{r(m['pivot_from_hull_centre_m'][0])}, {r(m['pivot_from_hull_centre_m'][1])}],
  }},""")
open(dest,'w').write("""/**
 * Generated by tools/photo-sprites/build.py from the per-vehicle configs; do not edit by hand.
 * Sizes are in metres. `hull` is drawn centred on the unit; `pivot` is the turret ring centre
 * relative to the hull centre (+x forward, +y right); `turret.pivot` is that point inside the turret image.
 */
export interface PhotoSpriteDef {
  hull: { file: string; w: number; h: number };
  turret: { file: string; w: number; h: number; pivot: [number, number] };
  pivot: [number, number];
}

export const PHOTO_SPRITES: Record<string, PhotoSpriteDef> = {
"""+"\n".join(ents)+"\n};\n")
