"""Write src/data/photoInfantry.ts and src/data/photoBuildings.ts from the outputs of
infantry.py and buildings.py.  usage: gen_infantry_buildings_ts.py INFANTRY_OUT ROOFS_OUT"""
import sys, json, glob, os
inf_dir, roof_dir = sys.argv[1], sys.argv[2]
r = lambda v: round(v, 3)
sets = {'iran': {'stand': [], 'prone': []}, 'iraq': {'stand': [], 'prone': []}}
for f in sorted(glob.glob(f'{inf_dir}/*.json')):
    m = json.load(open(f))
    sets[m['faction']][m['kind']].append(
        f"{{ file: '{m['file']}', w: {r(m['w'])}, h: {r(m['h'])}, anchor: [{r(m['anchor'][0])}, {r(m['anchor'][1])}] }}")
def lst(xs): return '[\n      ' + ',\n      '.join(xs) + ',\n    ]' if xs else '[]'
body = '\n'.join(f"  {fac}: {{\n    stand: {lst(s['stand'])},\n    prone: {lst(s['prone'])},\n  }}," for fac, s in sets.items())
open('src/data/photoInfantry.ts', 'w').write(f"""import type {{ FactionId }} from './units/types';

/**
 * Generated by tools/photo-sprites/gen_infantry_buildings_ts.py; do not edit by hand.
 * One entry per soldier figure cut out of a photo. Sizes are in metres before the renderer's
 * readability scale. The figure faces +x; `anchor` is the body centre inside the image.
 */
export interface InfantryPhotoDef {{ file: string; w: number; h: number; anchor: [number, number] }}

export const PHOTO_INFANTRY: Record<FactionId, {{ stand: InfantryPhotoDef[]; prone: InfantryPhotoDef[] }}> = {{
{body}
}};
""")
roofs = json.load(open(f'{roof_dir}/roofs.json'))
open('src/data/photoBuildings.ts', 'w').write("""/**
 * Generated by tools/photo-sprites/gen_infantry_buildings_ts.py; do not edit by hand.
 * Roof photos, each straightened to a square that fills one 16 m building tile.
 */
export const PHOTO_ROOFS: { file: string }[] = [
""" + ''.join(f"  {{ file: '{f}' }},\n" for f in roofs) + "];\n")
